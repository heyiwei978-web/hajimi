(function(){
  if(typeof templates==='undefined'||!Array.isArray(templates)||!window.HAJIMI_IDEAL_CASES||!window.HAJIMI_IDEAL_CASES.seeds)return;
  var seeds=window.HAJIMI_IDEAL_CASES.seeds;

  function region(c){
    var m={
      'TKA':'右膝','THA':'右髋及骨盆','人工股骨头置换':'左髋及骨盆','股骨转子间骨折':'右髋/股骨近端',
      '股骨大粗隆骨折':'左髋','股骨干骨折':'右股骨','胫骨干骨折':'左胫腓骨','胫骨平台骨折':'右膝/胫骨平台',
      '踝关节三踝骨折':'右踝','跟骨骨折':'左跟骨','桡骨远端骨折':'右腕','桡骨头骨折':'左肘',
      '肱骨近端骨折':'右肩/肱骨近端','肱骨干骨折':'左肱骨','锁骨骨折':'右锁骨','尺桡骨干骨折':'右前臂',
      '髌骨骨折':'左膝/髌骨','掌骨骨折':'右手','指骨骨折':'左环指','跖骨骨折':'右足','趾骨骨折':'右第一趾','骨盆骨折':'骨盆'
    };
    return m[c.group]||'患部';
  }
  function fixationWord(c){
    if(c.kind==='joint-knee'||c.kind==='joint-hip')return '假体稳定性及软组织平衡';
    return '骨折固定稳定性及软组织情况';
  }
  function structuralBasis(c){
    if(c.kind==='joint-knee')return '影像明确显示膝关节间隙变窄、软骨下骨硬化、骨赘及力线异常，与症状和查体一致。';
    if(c.kind==='joint-hip'&&c.group==='THA')return '影像明确显示股骨头坏死、塌陷及继发关节退变，与髋痛和活动受限相符。';
    if(c.kind==='joint-hip')return '影像明确显示移位性股骨颈骨折，与患肢短缩外旋及不能负重相符。';
    return '影像明确显示'+c.diagnosis+'的骨折线、移位或关节关系异常，与受伤机制及专科查体相符。';
  }
  function rehabGoal(c){
    var g=c.group;
    if(g==='TKA')return '控制术后疼痛和肿胀，恢复膝关节完全伸直并逐步提高屈曲活动度，激活股四头肌，完成安全床椅转移及助行器步行，出院前达到基本生活自理和居家康复能力。';
    if(g==='THA'||g==='人工股骨头置换')return '维持髋关节稳定和下肢肌力，掌握脱位预防动作，完成床椅转移及助行器步行，在不增加疼痛和跌倒风险的前提下恢复基本生活能力。';
    if(g==='股骨转子间骨折'||g==='股骨干骨折'||g==='骨盆骨折'||g==='股骨大粗隆骨折')return '维持髋膝踝活动及下肢肌力，减少卧床相关并发症，在固定允许范围内完成床椅转移和规定负重级别的步行训练。';
    if(g==='胫骨平台骨折')return '在保护平台内固定和关节面的前提下维持完全伸膝、逐步增加屈膝活动度，保持股四头肌力量和踝泵功能，同时严格执行非负重要求。';
    if(g==='胫骨干骨折')return '维持膝踝关节活动和下肢肌力，在髓内固定允许范围内逐步恢复分级负重和步态，避免膝踝僵硬。';
    if(g==='踝关节三踝骨折'||g==='跟骨骨折')return '控制足踝肿胀，维持足趾及允许范围内踝足活动，保护切口和内固定，保持患肢非负重并训练安全双拐/助行器转移。';
    if(g==='髌骨骨折')return '保护伸膝装置和张力带固定，保持股四头肌激活及完全伸膝，按固定稳定性逐步增加屈膝范围并恢复支具保护下步行。';
    if(g==='肱骨近端骨折')return '保护骨折固定及肩袖止点，维持手腕肘活动，循序进行钟摆、被动及主动辅助肩关节训练，重点预防肩关节僵硬。';
    if(g==='肱骨干骨折'||g==='锁骨骨折')return '保护内固定并维持上肢末梢神经功能，尽早恢复手腕肘活动和肩关节安全活动范围，避免长期悬吊导致肩肘僵硬。';
    if(g==='桡骨远端骨折'||g==='尺桡骨干骨折')return '控制手腕肿胀，保持手指、肘关节活动，在固定允许范围内逐步恢复腕及前臂旋转功能，预防肌腱粘连和关节僵硬。';
    if(g==='桡骨头骨折')return '在保护桡骨头固定和肘关节稳定的前提下尽早恢复肘屈伸及前臂旋转，重点预防肘关节僵硬和旋转受限。';
    if(g==='掌骨骨折'||g==='指骨骨折')return '控制手部肿胀，维持未受限关节活动，在稳定固定基础上尽早开展患指保护性屈伸，重点预防旋转畸形、肌腱粘连和关节僵硬。';
    if(g==='跖骨骨折'||g==='趾骨骨折')return '控制足部肿胀，维持足趾及踝关节活动，保护骨折固定和关节面，严格遵守当前负重限制并保持安全步态。';
    return '在保护手术部位稳定的前提下恢复肌力、活动度和基本生活能力。';
  }
  function imagingPlan(c){
    var r=region(c);
    if(c.kind==='joint-knee')return '术后早期复查右膝正侧位X线，评价假体位置、胫股力线及有无假体周围骨折，并据此确认负重与ROM训练方案。';
    if(c.kind==='joint-hip')return '术后早期复查骨盆正位及患髋X线，评价假体位置、髋关节复位、肢体长度及有无假体周围骨折，并据此确认负重与脱位预防方案。';
    if(['胫骨平台骨折','踝关节三踝骨折','跟骨骨折','桡骨远端骨折','桡骨头骨折','髌骨骨折','趾骨骨折'].includes(c.group))return '术后早期复查'+r+'正侧位及必要的关节专项X线，评价关节面/关节关系、内固定位置及有无继发移位，据此确定关节活动及负重限制。';
    return '术后早期复查'+r+'正侧位X线，评价骨折对位对线、内固定位置及有无继发移位，并据此调整后续康复。';
  }
  function dailyNext(c,day){
    var g=c.group;
    if(g==='TKA'){
      if(day===1)return '继续冰敷/抬高、踝泵及股四头肌激活，下一阶段增加助行器步行距离并将膝屈曲逐步推进至约75°。';
      if(day===2)return '继续留置引流管观察至次日，保持完全伸膝并将屈曲逐步推进至约90°，增加助行器步行距离。';
      if(day===3)return '拔除引流管后观察切口及肿胀，继续将膝屈曲推进至90°以上并提高步行耐力。';
      return '继续提高膝关节屈曲活动度、股四头肌力量和助行器步行耐力，训练后若疼痛或肿胀明显增加则下调强度。';
    }
    if(g==='THA'||g==='人工股骨头置换')return '继续髋关节脱位预防、踝泵及下肢肌力训练，在助行器保护下逐步增加步行距离和床椅转移独立性。';
    if(g==='胫骨平台骨折')return '继续支具保护下膝关节屈伸和股四头肌训练，保持患肢非负重，逐步提高床椅转移及助行器使用熟练度。';
    if(g==='踝关节三踝骨折'||g==='跟骨骨折')return '继续抬高消肿、足趾活动及允许范围内踝足训练，保持患肢非负重，重点观察切口/皮肤及足趾循环。';
    if(g==='桡骨头骨折')return '继续保护性肘屈伸和前臂旋转训练，逐日扩大无痛活动范围，避免提重物、撑地和轴向负荷。';
    if(g==='肱骨近端骨折')return '继续手腕肘活动和肩关节钟摆/主动辅助训练，避免抗阻外展及提重物，根据疼痛逐步增加肩前屈范围。';
    if(g==='桡骨远端骨折')return '继续抬高消肿和手指全范围活动，在固定允许范围内逐步增加腕关节及前臂旋转活动，重点观察正中神经症状。';
    if(g==='掌骨骨折'||g==='指骨骨折')return '继续手部抬高及未限制关节主动活动，在稳定固定基础上逐步增加患指屈伸次数和幅度，保持无旋转交叉。';
    if(g==='跖骨骨折'||g==='趾骨骨折')return '继续足部保护、抬高和足趾活动，严格遵守当前负重限制，训练安全步态并观察局部肿胀和末梢循环。';
    if(g==='肱骨干骨折')return '继续肩、肘、腕、手指主动活动并反复检查桡神经功能，暂避免上肢负重和抗阻训练。';
    if(g==='尺桡骨干骨折')return '继续手指、腕肘活动并逐步恢复前臂旋转，训练过程中观察正中、尺、桡神经功能及前臂肿胀。';
    if(g==='锁骨骨折')return '继续手腕肘活动和肩关节钟摆/主动辅助训练，暂避免提重物和强力外展上举。';
    if(g==='髌骨骨折')return '继续支具保护下股四头肌训练和分阶段屈膝，保持伸膝装置保护，避免无保护深屈膝。';
    return '继续患肢肌力、邻近关节活动和安全转移训练，活动强度依据疼痛、肿胀及固定稳定性逐步调整。';
  }

  templates.forEach(function(t){
    var c=seeds[t.group];
    if(!c||!t.sourceBody)return;
    var b=String(t.sourceBody);

    if(t.short==='入院记录'){
      b=b.replace('3. 影像学已明确显示相应骨折/关节结构异常，病史、体征及影像相互吻合。','3. '+structuralBasis(c));
      b=b.replace('5. 术后根据固定/假体稳定性尽早启动康复，并量化记录疼痛、关节活动度、肌力及步行/日常活动能力。','5. 术后根据'+fixationWord(c)+'尽早启动康复，并量化记录疼痛、活动度、肌力及与本病种相关的功能指标。');
    }

    if(t.short==='多学科术前讨论'){
      b=b.replace('术后按固定/假体稳定性尽早启动功能训练。','术后按'+fixationWord(c)+'尽早启动分阶段功能训练。');
      b=b.replace('应用透视/试模反复确认复位、内固定或假体位置','根据术式应用透视或试模反复确认复位质量及植入物位置');
    }

    if(t.short==='手术记录'){
      b=b.replace('适时复查术后DR。',imagingPlan(c));
    }

    if(t.short==='康复评估与训练记录'){
      b=b.replace(
        /二、本阶段康复目标\n[\s\S]*?\n\n三、训练内容/,
        '二、本阶段康复目标\n'+rehabGoal(c)+'\n\n三、训练内容'
      );
      b=b.replace('在保护手术固定/假体及软组织安全前提下，','');
      b=b.replace('恢复床椅转移及基本步行/上肢日常活动能力，','');
    }

    var m=String(t.short||'').match(/^术后第(\d+)天病程$/);
    if(m){
      var day=+m[1];
      b=b.replace(
        /下一步计划：继续切口观察和分阶段康复，根据疼痛、肌力、关节活动度及影像结果逐步增加活动量。/,
        '下一步计划：'+dailyNext(c,day)
      );
    }

    if(t.short==='术后首次病程记录'){
      b=b.replace(/复查相应部位正侧位\/关节专项X线/,'复查'+region(c)+'正侧位/关节专项X线');
      b=b.replace(/复查相应部位正侧位X线/,'复查'+region(c)+'正侧位X线');
    }

    if(t.short==='出院小结'){
      b=b.replace(/复查相应部位X线/,'复查'+region(c)+'X线');
    }

    t.sourceBody=b;
    t.qualityV12=true;
  });

  if(window.HAJIMI_RECORD_QUALITY_V10)window.HAJIMI_RECORD_QUALITY_V10.issues=[];
  var issues=[];
  templates.forEach(function(t){
    var b=String(t.sourceBody||'');
    if(/骨折\/关节结构异常|固定\/假体|步行\/上肢|复查相应部位|适时复查术后DR/.test(b))issues.push(t.group+' / '+t.short+'：仍有模板化斜杠或泛化部位');
    if(/^术后第\d+天病程$/.test(t.short)&&/逐步增加活动量/.test(b))issues.push(t.group+' / '+t.short+'：下一步计划仍泛化');
  });
  window.HAJIMI_RECORD_QUALITY_V12={enabled:true,issues:issues};
})();