import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {POLYPHONES} from './pinyin-initials.mjs';

function copyTree(source, target, filter) {
  fs.mkdirSync(target, {recursive: true});
  let count = 0;
  for (const entry of fs.readdirSync(source, {withFileTypes: true})) {
    const from = path.join(source, entry.name);
    const to = path.join(target, entry.name);
    if (entry.isDirectory()) count += copyTree(from, to, filter);
    else if (entry.isFile() && (!filter || filter(entry.name))) {
      fs.copyFileSync(from, to);
      count++;
    }
  }
  return count;
}

// Copies PDF.js runtime, worker, CJK CMaps and standard fonts from node_modules/pdfjs-dist
// into dist/assets/pdfjs/ so /materials/library runs 100% same-origin under strict CSP.
// Isolated build tests that copy only repository source directories without node_modules
// skip cleanly; CI and Vercel always install devDependencies before running npm run build.
export function copyPdfjsAssets(directory, root = new URL('../', import.meta.url)) {
  const pkgDir = path.join(fileURLToPath(root), 'node_modules', 'pdfjs-dist');
  if (!fs.existsSync(pkgDir)) return {copied: false, files: 0};

  const outDir = path.join(fileURLToPath(directory), 'assets', 'pdfjs');
  fs.mkdirSync(outDir, {recursive: true});
  let files = 0;

  for (const name of ['pdf.min.mjs', 'pdf.worker.min.mjs']) {
    const src = path.join(pkgDir, 'build', name);
    if (!fs.existsSync(src)) throw new Error('Missing pdfjs-dist build artifact: ' + name);
    fs.copyFileSync(src, path.join(outDir, name));
    files++;
  }

  const cmaps = path.join(pkgDir, 'cmaps');
  if (fs.existsSync(cmaps)) {
    files += copyTree(cmaps, path.join(outDir, 'cmaps'), name => name.endsWith('.bcmap'));
  }

  const fonts = path.join(pkgDir, 'standard_fonts');
  if (fs.existsSync(fonts)) {
    files += copyTree(fonts, path.join(outDir, 'standard_fonts'), name => /\.(?:pfb|ttf|otf)$/i.test(name));
  }

  return {copied: true, files};
}

// Compiles config/pinyin-initials.json + POLYPHONES into a browser helper in dist/pinyin-initials.js
// so /materials/library can compute Chinese pinyin initials on PDF upload and during search.
export function writePinyinRuntime(directory, root = new URL('../', import.meta.url)) {
  const byLetter = JSON.parse(fs.readFileSync(new URL('config/pinyin-initials.json', root), 'utf8'));
  const script = '/* Generated by scripts/pdfjs-build.mjs. Do not edit. */\n'
    + '(()=>{\n'
    + '  const byLetter=JSON.parse(' + JSON.stringify(JSON.stringify(byLetter)) + ');\n'
    + '  const poly=JSON.parse(' + JSON.stringify(JSON.stringify(POLYPHONES)) + ');\n'
    + '  const map=new Map();\n'
    + '  for(const [letter,chars] of Object.entries(byLetter))for(const ch of chars)map.set(ch,letter);\n'
    + '  function initialsOf(text,maxVariants=6){\n'
    + '    let variants=[\'\'];\n'
    + '    for(const ch of String(text??\'\')){\n'
    + '      if(!/[\\u3400-\\u9fff]/.test(ch))continue;\n'
    + '      const letters=poly[ch]||map.get(ch);\n'
    + '      if(!letters)continue;\n'
    + '      const next=[];\n'
    + '      for(const p of variants)for(const l of letters)if(next.length<maxVariants)next.push(p+l);\n'
    + '      variants=next;\n'
    + '    }\n'
    + '    return variants[0]?variants:[];\n'
    + '  }\n'
    + '  function textInitials(text,limit=6000){\n'
    + '    let out=\'\';\n'
    + '    for(const ch of String(text??\'\')){\n'
    + '      if(out.length>=limit)break;\n'
    + '      const l=map.get(ch);\n'
    + '      if(l)out+=l;\n'
    + '      else if(/[a-zA-Z0-9]/.test(ch))out+=ch.toLowerCase();\n'
    + '      else if(out.length&&out[out.length-1]!==\' \')out+=\' \';\n'
    + '    }\n'
    + '    return out.trim();\n'
    + '  }\n'
    + '  window.HAJIMI_PINYIN_INITIALS=Object.freeze({initialsOf,textInitials});\n'
    + '})();\n';
  fs.writeFileSync(new URL('pinyin-initials.js', directory), script);
}
