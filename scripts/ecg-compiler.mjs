import fs from 'node:fs';
import vm from 'node:vm';
import {createHash} from 'node:crypto';

// The ECG section is authored as several layered source files (base data,
// textbook batches that extend entries, sketches, calculators and the UI).
// At build time we run them once, validate the merged result and publish a
// single content-hashed bundle that can be cached forever.
const root=new URL('../',import.meta.url);
export const ECG_SOURCES=['ecg-data.js','ecg-cases-data.js','ecg-basics-data.js','ecg-periop-data.js','ecg-book-data.js','ecg-book-data-2.js','ecg-book-data-3.js','ecg-book-data-4.js','ecg-book-data-5.js','ecg-waveforms.js','ecg-calculators.js'];
const RUNTIME=['ecg-search.js','ecg-calipers.js','ecg.js'];

export function loadEcg(read=file=>fs.readFileSync(new URL(file,root),'utf8')){
  const context={window:{}};
  vm.createContext(context);
  for(const file of ECG_SOURCES)vm.runInContext(read(file),context,{filename:file,timeout:10000});
  return context.window;
}

export function validateEcg(window){
  const data=window.HAJIMI_ECG_DATA,sketch=window.HAJIMI_ECG_WAVEFORMS,errors=[];
  const fail=message=>errors.push(message);
  if(!data||!Array.isArray(data.entries))return ['HAJIMI_ECG_DATA.entries missing'];
  const kinds=new Set(sketch.kinds()),categories=new Set(data.categories.map(item=>item.id)),ids=new Set();
  const https=url=>{try{return new URL(url).protocol==='https:';}catch{return false;}};
  const nonEmpty=value=>typeof value==='string'&&value.trim().length>0;
  for(const entry of data.entries){
    const where='entry '+entry.id;
    if(!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.id||''))fail(where+': id must be a lowercase slug');
    if(ids.has(entry.id))fail(where+': duplicate id');
    ids.add(entry.id);
    if(!categories.has(entry.category))fail(where+': unknown category '+entry.category);
    if(!['high','medium','low'].includes(entry.risk))fail(where+': risk must be high, medium or low');
    if(!nonEmpty(entry.title)||!nonEmpty(entry.basic?.summary))fail(where+': title and summary are required');
    if(!kinds.has(entry.basic?.diagram?.kind))fail(where+': sketch "'+entry.basic?.diagram?.kind+'" does not exist');
    for(const key of ['diagnosticPoints','differentialPoints'])if(!Array.isArray(entry.basic?.[key])||!entry.basic[key].length)fail(where+': '+key+' required');
    for(const key of ['timing','anesthesia','postoperative','consultation'])if(!nonEmpty(entry.periop?.[key]))fail(where+': periop.'+key+' required');
    for(const reference of entry.references||[])if(!https(reference.url))fail(where+': reference must use https: '+reference.url);
    if(!/^\d{4}-\d{2}-\d{2}$/.test(entry.updatedAt||''))fail(where+': updatedAt must be YYYY-MM-DD');
  }
  for(const entry of data.entries)for(const id of entry.related||[])if(!ids.has(id))fail('entry '+entry.id+': related entry '+id+' does not exist');
  for(const item of data.cases||[]){
    if(!kinds.has(item.kind))fail('case '+item.id+': sketch "'+item.kind+'" does not exist');
    if(item.entry&&!ids.has(item.entry))fail('case '+item.id+': entry '+item.entry+' does not exist');
    if(!(item.answer>=0&&item.answer<item.options.length))fail('case '+item.id+': answer index out of range');
  }
  const P=data.periop||{};
  for(const item of P.scenarios||[])if(item.entry&&!ids.has(item.entry))fail('periop scenario '+item.title+': entry '+item.entry+' does not exist');
  for(const item of P.abnormal||[])if(item.entry&&!ids.has(item.entry))fail('periop finding '+item.finding+': entry '+item.entry+' does not exist');
  for(const item of P.anesthesia||[])if(item.link&&!ids.has(item.link))fail('anesthesia item '+item.title+': entry '+item.link+' does not exist');
  for(const item of data.basics?.artifacts||[])if(!kinds.has(item.kind))fail('artifact '+item.title+': sketch "'+item.kind+'" does not exist');
  return errors;
}

const digest=text=>createHash('sha256').update(text).digest('hex').slice(0,20);

export function compileEcg(directory,read=file=>fs.readFileSync(new URL(file,root),'utf8')){
  const window=loadEcg(read),errors=validateEcg(window);
  if(errors.length)throw new Error('ECG build failed:\n'+errors.join('\n'));
  // JSON.parse of a string literal is parsed faster than an equivalent object literal.
  const json=JSON.stringify(window.HAJIMI_ECG_DATA);
  const bundle='/* Generated by scripts/ecg-compiler.mjs. Edit the ecg-*.js sources instead. */\n'+
    'window.HAJIMI_ECG_DATA=JSON.parse('+JSON.stringify(json)+');\n'+
    ['ecg-waveforms.js','ecg-calculators.js',...RUNTIME].map(file=>read(file)).join('\n;\n');
  const name='ecg-'+digest(bundle)+'.js';
  fs.mkdirSync(new URL('assets/',directory),{recursive:true});
  fs.writeFileSync(new URL('assets/'+name,directory),bundle);
  const html=read('ecg.html');
  const scripts=[...html.matchAll(/<script defer src="\/(ecg[^"?]*\.js)\?[^"]*"><\/script>\n?/g)];
  const listed=scripts.map(match=>match[1]);
  const expected=[...ECG_SOURCES,...RUNTIME];
  if(listed.join()!==expected.join())throw new Error('ecg.html script order must be '+expected.join(', ')+'; found '+listed.join(', '));
  let output=html;
  for(const [tag]of scripts)output=output.replace(tag,'');
  output=output.replace('<script defer src="/workspace.js','<script defer src="/assets/'+name+'"></script>\n<script defer src="/workspace.js');
  fs.writeFileSync(new URL('ecg.html',directory),output);
  return {name,bytes:Buffer.byteLength(bundle),entries:window.HAJIMI_ECG_DATA.entries.length};
}
