  function treatmentRationale(c,day){
    var a=[];
    a.push('1. 疼痛管理：根据静息及活动VAS评分继续多模式镇痛。当前疼痛逐日下降，未出现进行性加重或与手术不相符的疼痛表现。');
    if(day===1){
      a.push('2. 抗菌药物管理：本例为清洁切口手术，围手术期预防性抗菌药物已按时使用；目前体温正常、切口干燥、无感染证据，预防性用药于术后24小时内结束，不无指征延长疗程。');
    }
    if(isLower(c)){
      a.push((day===1?'3. ':'2. ')+'静脉血栓预防：下肢/骨盆手术且术后活动受限，VTE风险较高；确认无活动性出血且肾功能正常后按院内方案继续药物预防，并配合踝泵、早期离床及机械预防。每日复评切口出血、血红蛋白及下肢症状后调整方案。');
    }else{
      a.push((day===1?'3. ':'2. ')+'卧床并发症及VTE预防：当前无额外高危因素，鼓励尽早离床及未受限关节主动活动；动态评估VTE风险，风险因素变化时及时调整预防策略。');
    }
    if(c.drain&&day===2){
      a.push('3. 引流管理：近24小时引流量已明显减少、颜色转淡，切口无活动性渗血，符合拔管条件；拔管后继续观察局部渗血、血肿及肿胀。');
    }
    if(day>=3){
      a.push('3. 康复决策：切口、疼痛、肌力及术后影像均符合预期，继续逐级增加关节活动、步行或上肢功能训练，训练范围不超过当前固定或假体允许程度。');
    }
    return a.join('\n');
  }
  function dischargeCheck(c,S){
    return '诊断一致性：入院诊断、术前诊断、术中诊断及出院诊断均为“'+c.diagnosis+'”，住院期间无新增疾病诊断。\n'+
      '手术一致性：'+S+'实际完成“'+surgeryName(c)+'”，与手术记录、术后首次病程及出院记录一致。\n'+
      '转归一致性：术后疼痛逐日减轻，切口愈合趋势良好，患肢神经血管状态正常，复查影像未见影响出院的异常，功能达到本阶段出院目标。';
  }
  function dateFrom(body,label){
    var re=new RegExp(label+'：(\\d{4}-\\d{2}-\\d{2})');
    var m=String(body||'').match(re);
    return m?m[1]:'';
  }

