  function formatOperation(body, t) {
    var s = String(body || '').replace(/\r\n/g, '\n');
    if (!s) return s;
    var c = seeds[t.group] || null;
    if (t.specialCase) {
      amended.preservedSpecial++;
      return s;
    }
    if (!c) return s;
    var op = String(c.surgery || ''), diagnosis = String(c.diagnosis || '');
    // Revision, staged infection, tumor, tendon and spine surgery require a procedure-specific protocol.
    // Do not overwrite their unique operative findings with an unrelated standard fracture approach.
    var complex = /翻修|感染|肿瘤|植皮|肌腱|神经移植|椎间|脊柱|椎体|骨髓炎|清创|截肢|截趾|松解|截骨|骨不连|内生软骨瘤|滑膜炎/.test(op + diagnosis);
    var tech = complex ? null : technique(c);
    var anchor = s.search(/手术经过[：:]/);
    if (anchor < 0) return s;
    var prefix = s.slice(0, anchor);
    var rest = s.slice(anchor);
    var end = rest.search(/\n(?:术后计划|术后医嘱|术后处理|术者签名|手术者签名)[：:]/);
    var suffix = end >= 0 ? rest.slice(end).trim() : '';
    var inner = end >= 0 ? rest.slice(0, end) : rest;
    if (!tech) {
      // Preserve atypical operative details; adjust only clearly numbered step-by-step formatting.
      if (inner.length >= 650) return s;
      var manual = String(c.procedure || '').trim();
      if (!manual) return s;
      var prep = '患者入室后核对身份、手术名称及侧别，麻醉满意后取' + (c.position || '适当体位') + '，常规消毒、铺无菌巾单；依据术前影像和实际手术方案定位切口，分层显露病变区域，妥善保护重要神经血管及邻近软组织。';
      var step = '按术前方案显露并核实术中病变范围，结合直视及必要影像进行相应处理。' + manual;
      var verify = '在术中复核责任结构处理结果、稳定性及神经血管保护情况，并根据实际病变范围决定是否需要额外修复或取材送检；植入物名称、规格、数量和标本信息应与手术器械及病理记录相符。';
      var closure = '充分冲洗术野，严密止血，逐项清点器械、纱布和缝针，按实际放置引流，分层关闭切口并覆盖无菌敷料；术中出血量、输血情况和并发症以麻醉及手术原始记录为准。';
      amended.operations++;
      return prefix + '手术经过：\n' + [prep, step, verify, closure].join('\n\n') + (suffix ? '\n\n' + suffix : '');
    }
    amended.approaches[tech.name] = (amended.approaches[tech.name] || 0) + 1;
    amended.operations++;
    var p1 = '患者入手术室后核对姓名、住院号、手术名称及' + (c.side || '患') + '侧手术标记，完成手术安全核查；' +
      (c.anesthesia || '按麻醉记录所示麻醉') + '满意后取' + (c.position || '术式要求体位') + '，安放保护垫，常规消毒、铺无菌巾单。' + tech.approach;
    var p2 = tech.expose;
    var p3 = tech.fixation;
    var procedure = String(c.procedure || '');
    // Preserve special additions (e.g. concomitant tendon or ligament repair), but not a duplicate of routine preparation.
    if (/肩袖修补|植骨|髌韧带|韧带修复|铆钉|锚钉|特殊处理/.test(procedure) && !/全膝关节置换/.test(op)) {
      p3 += ' 原病例记载的附加处理：' + procedure;
    }
    var p4 = tech.confirm + ' 随后充分冲洗手术野，反复检查有无活动性出血，核对内固定或假体牢固程度及邻近组织无明显卡压。' +
      (c.drain ? '按原病例记录留置切口引流管并妥善固定。' : '原病例未放置切口引流管。') +
      ' 分层修复深筋膜及软组织，关闭皮下和皮肤，无菌敷料包扎；器械、缝针、纱布清点无误。' +
      (typeof c.bloodloss === 'number' ? '原病例记录术中出血约' + c.bloodloss + 'ml。' : '术中出血量以实际记录为准。') +
      ' 术毕检查患肢血运及神经功能，核对植入物追溯信息，按麻醉苏醒情况安全转运。';
    return prefix + '手术经过：\n' + [p1,p2,p3,p4].join('\n\n') + (suffix ? '\n\n' + suffix : '');
  }

